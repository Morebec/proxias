package proxias

import "io"

// CompletionMessageRole defines the role of a message in the chat completion.
// In other words it allows indicating who generated a particular message in the chat history.
type CompletionMessageRole string

const (
	// CompletionMessageRoleUser represents a user message in the chat completion.
	// Purpose: Contains the prompt, questions, or instructions sent by a human user.
	// Origin: Provided by the end-user interacting with an application/harness.
	CompletionMessageRoleUser CompletionMessageRole = "user"

	// CompletionMessageRoleSystem represents a system message in the chat completion.
	// See CompletionMessageRoleDeveloper for more details.
	CompletionMessageRoleSystem CompletionMessageRole = "system"

	// CompletionMessageRoleDeveloper formally "system", represents an internal message.
	// Purpose: indicates that a message sets the persona, behavior, boundaries, and global context of the model.
	// Essentially guides the model's tone or dicatates formatting rules (e.g. "always return JSON"),
	// dictates guardrails, constraints, or safety measures for the model's behavior.
	// In most models it carries the highest level of authority over the model's behavior.
	// Origin: Usually set by harness/application developers, hidden from users.
	CompletionMessageRoleDeveloper CompletionMessageRole = "developer"

	// CompletionMessageRoleAssistant represents an assistant message in the chat completion.
	// Purpose: Store the model's generated responses. Used to feed conversation history back to the model.
	// Because chat completion APIs are generally stateless, this provides a mechanism to maintain conversation
	// context across multiple turns.
	// Can also be used for few-shots prompting to mock how user and assistant turns to show the model how it should behave.
	// Origin: Generated by the model in response to user and system messages, or by backend code/harnesses when few-shots prompting is used.
	CompletionMessageRoleAssistant CompletionMessageRole = "assistant"

	// CompletionMessageRoleFunction represents a function message in the chat completion.
	// See CompletionMessageRoleTool for more details.
	CompletionMessageRoleFunction CompletionMessageRole = "function"

	// CompletionMessageRoleTool represents a tool message in the chat completion.
	// Purpose: Passes the output/results of an external function back to the model after a tool call.
	// When a model calls an external tool, it stops generating text responses and outputs
	// "tool calls" requests instead. Code runs these tools locally and passes the output back to the model.
	// using the tool role, so the model can read it and formulate its final answer.
	// Origin: Executed by backend code.
	CompletionMessageRoleTool CompletionMessageRole = "tool"
)

// CompletionRequest represents a chat completion request as received from the harness.
type CompletionRequest struct {
	// Stream indicates whether the chat completion request should be streamed as asked by the harness.
	Stream bool

	// Model is the model to be used for the chat completion request as requested by the harness.
	Model string

	// Messages are the chat completion messages said so far, the one to complete last as sent by the harness.
	Messages []CompletionMessage

	// Request is the chat completion request as the harness sent it, byte for byte.
	Request []byte
}

// LastMessage is the last of the messages, the one to complete, or the zero CompletionMessage if there are none.
func (r CompletionRequest) LastMessage() CompletionMessage {
	if len(r.Messages) == 0 {
		return CompletionMessage{}
	}
	return r.Messages[len(r.Messages)-1]
}

// CompletionMessage is one message of a CompletionRequest.
type CompletionMessage struct {
	Role    CompletionMessageRole
	Content []byte
}

// HasToolRole tells whether the message holds the result of a tool (or, formerly, of a function) that ran,
// as opposed to a message of a user or of a model.
func (m CompletionMessage) HasToolRole() bool {
	return m.Role == CompletionMessageRoleTool || m.Role == CompletionMessageRoleFunction
}

// CompletionResponse is what the ControlPlane answers: an HTTP-like response that the host writes back to
// its client, a stream included. Proxias never looks into Body.
//
// Whoever receives a CompletionResponse owns its Body, if there is one, and must close it. A response that
// comes with an error has none.
type CompletionResponse struct {
	// Status is the HTTP status code of the response.
	Status int
	// ContentType is the media type of Body: "application/json", "text/event-stream" for a stream...
	ContentType string
	// Body is the content of the response, if any.
	Body io.ReadCloser
}
